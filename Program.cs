using System.Globalization;
using Variant29_MobSpawner.Patterns;
CultureInfo.DefaultThreadCurrentCulture = CultureInfo.GetCultureInfo("ru-RU");
Console.OutputEncoding = System.Text.Encoding.UTF8;
Console.WriteLine("=== Вариант 29. Спавнер мобов в игре ===");
Console.WriteLine("Демонстрация паттернов Flyweight и Factory Method\n");
var sharedTypes = new MobArchetypeFactory();
var goblinFactory = new GoblinFactory(sharedTypes);
var skeletonFactory = new SkeletonFactory(sharedTypes);
var dragonFactory = new DragonFactory(sharedTypes);
var spawner = new MobSpawner();
Console.WriteLine("1. Спавним волну мобов разных типов:");
var goblin1 = spawner.Spawn(goblinFactory, 2, 4);
var goblin2 = spawner.Spawn(goblinFactory, 5, 4);
spawner.Spawn(goblinFactory, 7, 8);
var skeleton1 = spawner.Spawn(skeletonFactory, 10, 3);
spawner.Spawn(skeletonFactory, 12, 6);
spawner.Spawn(dragonFactory, 20, 10);
spawner.PrintWave();
Console.WriteLine("\n2. Проверяем разделение общих данных (Flyweight):");
Console.WriteLine($"  У гоблинов #{goblin1.Id} и #{goblin2.Id} один объект типа: {ReferenceEquals(goblin1.Archetype, goblin2.Archetype)}");
Console.WriteLine($"  У гоблина и скелета разные объекты типа: {!ReferenceEquals(goblin1.Archetype, skeleton1.Archetype)}");
Console.WriteLine($"  Общих объектов типов: {sharedTypes.Count}; мобов создано: {spawner.Spawned.Count}.");
Console.WriteLine("\n3. Индивидуальное здоровье:");
Console.WriteLine($"  До урона: гоблин #{goblin1.Id} HP={goblin1.Health}, гоблин #{goblin2.Id} HP={goblin2.Health}");
goblin1.TakeDamage(15);
Console.WriteLine($"  После 15 урона: гоблин #{goblin1.Id} HP={goblin1.Health}, гоблин #{goblin2.Id} HP={goblin2.Health}");
Console.WriteLine("  Здоровье изменилось только у первого экземпляра.");
Console.WriteLine("\n4. Общие данные типов:");
foreach (var archetype in sharedTypes.GetAll()) Console.WriteLine("  " + archetype);
Console.WriteLine("\nДемонстрация завершена.");
